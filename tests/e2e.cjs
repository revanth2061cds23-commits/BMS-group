  await mem.waitForSelector('text=is held for you')
  await shot(mem, '07b-member-live')
  await mem.click('button:has-text("for my seat")')
  await mem.click('text=Payment succeeds')
  await mem.waitForURL(/ticket/)
  await mem.waitForTimeout(400)
  await shot(mem, '09-ticket')
  // host sees update
  const t0 = Date.now()
