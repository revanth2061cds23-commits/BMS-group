  await sel.selectOption(opt)
  await host.click('text=Payment fails')
  const kopt = await sel.locator('option', { hasText: 'Karan' }).getAttribute('value')
  await sel.selectOption(kopt)
  await host.click('button:has-text("Declines")')
  await host.click('[aria-label="Close facilitator panel"]')
  await host.waitForTimeout(300)
  await shot(host, '05b-live-after-sims')
  // E13: move Aman's paid seat
  await host.click('[aria-label^="Seat F6 "]')
  await host.click('[aria-label="Seat F10 target"]')
  await mem.waitForSelector('text=Move to F10?')
  await shot(mem, '13-move-request')
  await mem.click('button:has-text("Move to F10")')
